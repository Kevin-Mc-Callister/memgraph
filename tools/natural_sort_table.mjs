// Generates src/utils/natural_sort_table.hpp for memgraph's naturalSortKey()
// from ICU (Node's Intl.Collator, root/en-US, numeric, base strength).
//
// Every code point in RANGES is classified the way the collator treats it at
// base strength:
//   ignore  - compares equal to nothing ("a" + c + "b" == "ab"): control
//             characters, combining marks, soft hyphen...
//   letter  - equal to a string of a-z (é -> e, ß -> ss, æ -> ae)
//   mark    - sorts before digits (whitespace, punctuation, most symbols);
//             gets a rank in the collator's order, equal characters share it
//   (none)  - anything else is copied to the key as UTF-8, which sorts after
//             every ASCII letter
// ASCII letters and digits are handled in code, not in the table.
import fs from 'fs';

const C = new Intl.Collator('en-US', {numeric: true, sensitivity: 'base'});
const RANGES = [[0x00, 0x7f], [0x80, 0x24f], [0x300, 0x36f], [0x2000, 0x206f]];
const EXPANSIONS = {
  'ß': 'ss',
  'æ': 'ae',
  'Æ': 'ae',
  'œ': 'oe',
  'Œ': 'oe',
  'ø': 'o',
  'Ø': 'o',
  'đ': 'd',
  'Đ': 'd',
  'ł': 'l',
  'Ł': 'l',
  'ħ': 'h',
  'Ħ': 'h'
};

const ignore = [], letters = [], marks = [];
for (const [lo, hi] of RANGES) {
  for (let cp = lo; cp <= hi; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const c = String.fromCodePoint(cp);
    if (/[A-Za-z0-9]/.test(c)) continue;
    if (C.compare('a' + c + 'b', 'ab') === 0) {
      ignore.push(cp);
      continue;
    }
    if (/\p{L}/u.test(c)) {
      const base = EXPANSIONS[c] ??
          c.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase();
      if (/^[a-z]+$/.test(base) && C.compare(c, base) === 0)
        letters.push([cp, base]);
      continue;
    }
    if (C.compare(c, '0') < 0) marks.push(cp);
  }
}
marks.sort(
    (a, b) =>
        C.compare(String.fromCodePoint(a), String.fromCodePoint(b)) || a - b);
const rankOf = new Map();
let rank = 0;
marks.forEach((cp, i) => {
  if (i === 0 ||
      C.compare(
          String.fromCodePoint(marks[i - 1]), String.fromCodePoint(cp)) !== 0)
    rank++;
  rankOf.set(cp, rank);
});
if (rank > 0x7f) throw new Error(`too many mark ranks: ${rank}`);

const entries = [
  ...ignore.map((cp) => [cp, 'kIgnore', 0, '']),
  ...letters.map(([cp, base]) => [cp, 'kLetter', 0, base]),
  ...marks.map((cp) => [cp, 'kMark', rankOf.get(cp), '']),
].sort((a, b) => a[0] - b[0]);

const hex = (cp) => '0x' + cp.toString(16).toUpperCase().padStart(4, '0');
const rows = entries.map(
    ([cp, kind, r, base]) =>
        `    {${hex(cp)}, Kind::${kind}, ${r}, "${base}"},`);
